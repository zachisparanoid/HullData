// Scans bundled imagery and regenerates src/lib/imageManifest.ts.
//
// Drop-in convention (no DB change needed — the query layer overlays this):
//   public/brands/<manufacturer-slug>.{jpg,jpeg,png,webp,avif}   -> brand photo
//   public/boats/<manufacturer-slug>/<model-key>.{jpg,...}        -> exact model photo
//
// <model-key> is the model name lowercased with non-alphanumerics collapsed to
// "-" (e.g. "GT54" -> "gt54", "54 Convertible" -> "54-convertible").
//
// Run with: npm run sync:images   (also runs automatically on prebuild)
import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const PUBLIC = join(ROOT, "public");
const IMG_EXT = /\.(jpe?g|png|webp|avif|gif)$/i;

const stripExt = (f) => f.replace(IMG_EXT, "");

function listImages(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => IMG_EXT.test(f) && statSync(join(dir, f)).isFile());
}

// Brand images
const brands = {};
for (const f of listImages(join(PUBLIC, "brands"))) {
  brands[stripExt(f)] = `/brands/${f}`;
}

// Per-model images, grouped by manufacturer slug (subfolder name)
const models = {};
const boatsDir = join(PUBLIC, "boats");
if (existsSync(boatsDir)) {
  for (const slug of readdirSync(boatsDir)) {
    const sub = join(boatsDir, slug);
    if (!statSync(sub).isDirectory()) continue;
    const files = listImages(sub);
    if (files.length === 0) continue;
    models[slug] = {};
    for (const f of files) models[slug][stripExt(f)] = `/boats/${slug}/${f}`;
  }
}

const brandCount = Object.keys(brands).length;
const modelCount = Object.values(models).reduce(
  (a, m) => a + Object.keys(m).length,
  0,
);

const out = `// AUTO-GENERATED by scripts/sync-images.mjs — do not edit by hand.
// Run \`npm run sync:images\` after adding files under public/brands or public/boats.
export const brandImages: Record<string, string> = ${JSON.stringify(brands, null, 2)};

export const modelImages: Record<string, Record<string, string>> = ${JSON.stringify(models, null, 2)};
`;

writeFileSync(join(ROOT, "src", "lib", "imageManifest.ts"), out);
console.log(
  `🖼  Image manifest synced: ${brandCount} brand images, ${modelCount} model images.`,
);
